pub fn read_lines(path: &str) -> impl Iterator<Item = String> {
    let file = File::open(path).unwrap();
    BufReader::new(file).lines().map(|l| l.unwrap())
}

/// Drops the delay-heuristic row (`node <id> <name> [..]`) so nodes only carry `NoManagement`.
fn strip_delay_row(line: String) -> String {
    match line.trim_start().starts_with("node") {
        true => line
            .split_once('[')
            .map_or(line.clone(), |(node, _)| node.to_string()),
        false => line,
    }
}

/// `100.cp` without its delay-heuristic rows.
pub fn load_100cp() -> ContactPlan<NoManagement, CM> {
    parse_from_iter(read_lines(PLAN_100CP).map(strip_delay_row)).unwrap()
}

/// `100.cp` with its delay-heuristic rows.
pub fn load_100cp_delay() -> ContactPlan<DelayNM, CM> {
    parse_from_iter(read_lines(PLAN_100CP)).unwrap()
}

/// Parses the tvgutil P-TVG at `path`. With `zero_delays`, every contact delay is set to 0.
/// Also returns the node names: they are only kept with the "debug" feature, and the
/// parser numbers the vertices in the order of the JSON object.
pub fn load_tvg(path: &str, zero_delays: bool) -> (ContactPlan<NoManagement, CM>, Vec<String>) {
    let file = File::open(path).unwrap();
    let mut json: Value = serde_json::from_reader(BufReader::new(file)).unwrap();
    if zero_delays {
        // contact = [tx, rx, start, end, [[_, confidence, [[start, rate, delay], ..]], ..]]
        for edge in json["edges"].as_array_mut().unwrap() {
            for contact in edge["contacts"].as_array_mut().unwrap() {
                for generation in contact[4].as_array_mut().unwrap() {
                    for characteristic in generation[2].as_array_mut().unwrap() {
                        characteristic[2] = 0.0.into();
                    }
                }
            }
        }
    }
    let names = json["vertices"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    (TVGUtilContactPlan::parse(json).unwrap(), names)
}

/// Index of the node called `node` in `names`.
pub fn node_index(names: &[String], node: &str) -> usize {
    names
        .iter()
        .position(|n| n == node)
        .unwrap_or_else(|| panic!("no node {node}"))
}

/// Start of the first contact and end of the last one.
pub fn plan_span<NM: a_sabr::node_manager::NodeManager>(
    plan: &ContactPlan<NM, CM>,
) -> (Date, Date) {
    let start = plan.contacts.iter().map(|(c, ..)| c.lifespan.start).min();
    let end = plan.contacts.iter().map(|(c, ..)| c.lifespan.end).max();
    (start.unwrap(), end.unwrap())
}

/// A routing request: source and destination node IDs, and start time.
#[derive(Clone, Copy)]
pub struct Query {
    pub source: usize,
    pub dest: usize,
    pub time: Date,
}

/// SplitMix64, so the queries only depend on the seed.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
}

/// `n` queries between two different `endpoints`, starting uniformly in `span`.
fn sample_queries(rng: &mut Rng, endpoints: &[usize], span: (Date, Date), n: usize) -> Vec<Query> {
    let (start, end) = span;
    (0..n)
        .map(|_| {
            let source = endpoints[rng.below(endpoints.len())];
            let dest = loop {
                let dest = endpoints[rng.below(endpoints.len())];
                if dest != source {
                    break dest;
                }
            };
            let time = start + (rng.next() % (end - start) as u64) as Date;
            Query { source, dest, time }
        })
        .collect()
}

/// The value of the environment variable `var`, or `default` if it is not set.
pub fn env_or(var: &str, default: usize) -> usize {
    std::env::var(var).map_or(default, |v| v.parse().unwrap())
}

/// Whether `SWEEP_PLANS` (comma-separated plan names, default: all) includes `name`.
pub fn plan_selected(name: &str) -> bool {
    std::env::var("SWEEP_PLANS").map_or(true, |plans| plans.split(',').any(|p| p == name))
}

/// `SWEEP_QUERIES` (default 100) queries of the plan `name` between two different
/// `endpoints`, starting uniformly over the span of `plan`. Each plan has its own random
/// stream (`SWEEP_SEED`, default 1, and the plan name), so selecting plans does not
/// change the others' queries.
pub fn plan_queries<NM: NodeManager>(
    name: &str,
    plan: &ContactPlan<NM, CM>,
    endpoints: &[usize],
) -> Vec<Query> {
    // FNV-1a of the name
    let name_hash = name.bytes().fold(0xCBF2_9CE4_8422_2325_u64, |h, b| {
        (h ^ b as u64).wrapping_mul(0x100_0000_01B3)
    });
    let mut rng = Rng(env_or("SWEEP_SEED", 1) as u64 ^ name_hash);
    let n = env_or("SWEEP_QUERIES", 100);
    sample_queries(&mut rng, endpoints, plan_span(plan), n)
}

/// Indices of the ground stations (`gs...`) among the node `names` of a LEO plan.
pub fn ground_stations(names: &[String]) -> Vec<usize> {
    names
        .iter()
        .enumerate()
        .filter(|(_, n)| n.starts_with("gs"))
        .map(|(i, _)| i)
        .collect()
}

thread_local! {
    static EXPANDED: Cell<usize> = const { Cell::new(0) };
}

/// Number of expansions counted by `Counting` since the last `reset_expanded`, for one
/// search: `dijkstra` stops when it pops the destination, without expanding it, but
/// `Counting` already counted that pop, so it is removed when `reached_dest`.
pub fn expanded(reached_dest: bool) -> usize {
    EXPANDED.get() - usize::from(reached_dest)
}

/// Sets the expansion counter back to 0.
pub fn reset_expanded() {
    EXPANDED.set(0);
}

/// Dijkstra work area `W` that counts the popped paths that are still relevant and reach a
/// real node: `dijkstra` explores their neighbors (expands them), except for the
/// destination (see `expanded`). With node parenting it counts nodes, with contact /
/// hybrid parenting it counts labels.
pub struct Counting<W>(W);

impl<'id, NM, CM, De, W> DijkstraWorkspace<'id, NM, CM, De> for Counting<W>
where
    NM: NodeManager,
    CM: ContactManager,
    De: FindableDest<'id, NM, CM>,
    W: DijkstraWorkspace<'id, NM, CM, De>,
{
    fn new(graph: &Multigraph<'id, NM, CM>) -> Self {
        Self(W::new(graph))
    }

    fn into_pathfinding_output<'a>(self) -> PathFindingOutput<'id, 'a> {
        self.0.into_pathfinding_output()
    }

    fn try_insert(
        &mut self,
        proposition: PathFragment<'id>,
        node: RoutableNodeRef<'id>,
        graph: &Multigraph<'id, NM, CM>,
        bundle: &Bundle,
        dest: &De,
    ) -> Option<usize> {
        self.0.try_insert(proposition, node, graph, bundle, dest)
    }

    fn node_check(&mut self, node: RoutableNodeRef<'id>, graph: &Multigraph<'id, NM, CM>) -> bool {
        self.0.node_check(node, graph)
    }

    fn poped_relevant_new(
        &mut self,
        frag: PathFragment<'id>,
        node: RoutableNodeRef<'id>,
        viaref: usize,
    ) -> (bool, bool, Option<INodeRef<'id>>) {
        let result = self.0.poped_relevant_new(frag, node, viaref);
        // `dijkstra` only explores the neighbors of relevant paths to real nodes
        if result.0 && matches!(node, RoutableNodeRef::I(_)) {
            EXPANDED.set(EXPANDED.get() + 1);
        }
        result
    }
}

/// `NodeParenting` counting its expansions.
pub type CountedNodeParenting<'id, D, Q = D> = Dijkstra<Counting<NodeParentingWorkArea<'id, D>>, Q>;
/// `HybridParenting` counting its expansions.
pub type CountedHybridParenting<'id, D, NM, CM, Q = D> =
    Dijkstra<Counting<HybridParentingWorkArea<'id, NM, CM, D>>, Q>;
/// `ContactParenting` counting its expansions.
pub type CountedContactParenting<'id, NM, CM, D, De, Q = D> =
    Dijkstra<Counting<ContactParentingWorkArea<'id, NM, CM, D, De>>, Q>;
