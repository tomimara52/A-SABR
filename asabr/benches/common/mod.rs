pub fn read_lines(path: &str) -> impl Iterator<Item = String> {
    let file = File::open(path).unwrap();
    BufReader::new(file).lines().map(|l| l.unwrap())
}

/// Drops the delay-heuristic row (`node <id> <name> [..]`) so nodes only carry `NoManagement`.
fn strip_delay_row(line: String) -> String {
    match line.trim_start().starts_with("node") {
        true => line
            .split_once('[')
            .map_or(line.clone(), |(node, _)| node.to_string()),
        false => line,
    }
}

/// `100.cp` without its delay-heuristic rows.
pub fn load_100cp() -> ContactPlan<NoManagement, CM> {
    parse_from_iter(read_lines(PLAN_100CP).map(strip_delay_row)).unwrap()
}

/// `100.cp` with its delay-heuristic rows.
pub fn load_100cp_delay() -> ContactPlan<DelayNM, CM> {
    parse_from_iter(read_lines(PLAN_100CP)).unwrap()
}

/// Parses the tvgutil P-TVG at `path`. With `zero_delays`, every contact delay is set to 0.
/// Also returns the node names: they are only kept with the "debug" feature, and the
/// parser numbers the vertices in the order of the JSON object.
pub fn load_tvg(path: &str, zero_delays: bool) -> (ContactPlan<NoManagement, CM>, Vec<String>) {
    let file = File::open(path).unwrap();
    let mut json: Value = serde_json::from_reader(BufReader::new(file)).unwrap();
    if zero_delays {
        // contact = [tx, rx, start, end, [[_, confidence, [[start, rate, delay], ..]], ..]]
        for edge in json["edges"].as_array_mut().unwrap() {
            for contact in edge["contacts"].as_array_mut().unwrap() {
                for generation in contact[4].as_array_mut().unwrap() {
                    for characteristic in generation[2].as_array_mut().unwrap() {
                        characteristic[2] = 0.0.into();
                    }
                }
            }
        }
    }
    let names = json["vertices"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    (TVGUtilContactPlan::parse(json).unwrap(), names)
}

/// Index of the node called `node` in `names`.
pub fn node_index(names: &[String], node: &str) -> usize {
    names
        .iter()
        .position(|n| n == node)
        .unwrap_or_else(|| panic!("no node {node}"))
}

/// Start of the first contact and end of the last one.
pub fn plan_span<NM: a_sabr::node_manager::NodeManager>(
    plan: &ContactPlan<NM, CM>,
) -> (Date, Date) {
    let start = plan.contacts.iter().map(|(c, ..)| c.lifespan.start).min();
    let end = plan.contacts.iter().map(|(c, ..)| c.lifespan.end).max();
    (start.unwrap(), end.unwrap())
}
